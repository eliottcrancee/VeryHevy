/**
 * Internationalisation FR/EN.
 *
 * - `t(key, vars?)` : utilisable partout (composants ET lib passe-partout),
 *   lit la langue depuis le store. Repli FR puis clé elle-même → aucun
 *   écran ne casse si une clé manque dans une langue.
 * - `useLang()` : à appeler dans tout composant utilisant t() pour
 *   re-rendre au changement de langue.
 * - Contenu utilisateur (titres, descriptions, posts, noms d'exos perso)
 *   n'est JAMAIS traduit : on ne traduit que l'interface.
 */
import { useStore } from '@/store/store'

export type Lang = 'fr' | 'en'
export type Vars = Record<string, string | number | undefined>
type Entry = string | ((v: Vars) => string)

export function detectLang(): Lang {
  try {
    const nav = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : ''
    if (nav.startsWith('en')) return 'en'
  } catch { /* ignore */ }
  return 'fr'
}

/** Code locale Intl pour la langue d'interface. */
export function localeOf(lang: Lang): string {
  return lang === 'en' ? 'en-US' : 'fr-FR'
}

/** Langue courante (hors React). */
export function currentLang(): Lang {
  try {
    return useStore.getState().settings.lang ?? 'fr'
  } catch {
    return 'fr'
  }
}

/** Réapplique <html lang> (SEO/lecteurs d'écran). */
export function applyLangAttr(lang: Lang): void {
  try {
    document.documentElement.lang = lang
  } catch { /* ignore */ }
}

export function useLang(): Lang {
  const lang = useStore((s) => s.settings.lang ?? 'fr')
  return lang
}

const fill = (s: string, vars: Vars): string =>
  s.replace(/\{(\w+)\}/g, (_, k: string) => {
    const v = vars[k]
    return v === undefined ? '' : String(v)
  });

export function t(key: string, vars?: Vars): string {
  const lang = currentLang()
  const v = vars ?? {}
  const entry: Entry | undefined = dict[lang][key] ?? dict.fr[key]
  if (entry === undefined) return key
  return fill(typeof entry === 'function' ? entry(v) : entry, v)
}

